// 차시 나누기 — 입장 페이지에서 1차시 · 2차시를 고르면 그 차시의 탭과 카드만 보인다.
// DOM 을 쓰지 않는다(시험이 그대로 불러다 본다). 탭 모듈은 부르지 않고 탭 id · 카드 id 로만 가리킨다.
//
// 카드 하나는 언제나 한 차시에만 속한다 — 그래서 주소(#탭/카드)만 보고도 몇 차시인지 알 수 있고,
// 예전 주소·「다음 시간에 이어하기」 파일·비상 사본에 적힌 주소가 그대로 맞는 차시로 열린다.

export const 차시들 = [
  {
    번호: 1,
    제목: '연관 분석과 세 가지 지표',
    목표: '연관 규칙을 읽고 지지도·신뢰도·향상도를 직접 계산한다',
    범위: { open: '*', measure: '*', find: ['sheet'] },
  },
  {
    번호: 2,
    제목: '연관 규칙 찾기와 Apriori',
    목표: '좋은 연관 규칙을 골라내고 Apriori 로 빈번 집합을 찾는다',
    범위: { find: ['explore', 'good'], apriori: '*', wrap: '*' },
  },
];

const 들어있나 = (범위, 탭id, 카드id) => {
  const 고른 = 범위[탭id];
  if (!고른) return false;
  return 카드id == null || 고른 === '*' || 고른.includes(카드id);
};

/** 그 차시에 보이는 탭과 카드 — [{ 탭, 카드: [...] }]. 탭·카드 차례는 원래 차례 그대로, 카드가 없는 탭은 뺀다 */
export function 차시보기(탭들, 번호) {
  const 차시 = 차시들.find(s => s.번호 === 번호);
  if (!차시) return [];
  return 탭들
    .map(탭 => ({ 탭, 카드: 탭.카드.filter(c => 들어있나(차시.범위, 탭.id, c.id)) }))
    .filter(v => v.카드.length);
}

/** 이 카드가 몇 차시인가 — 카드 id 가 없거나 모르는 카드면 그 탭이 처음 나오는 차시. 어디에도 없으면 0 */
export function 차시찾기(탭들, 탭id, 카드id) {
  const 탭 = 탭들.find(t => t.id === 탭id);
  if (!탭) return 0;
  const 아는카드 = 카드id != null && 탭.카드.some(c => c.id === 카드id);
  const s = 차시들.find(x => 들어있나(x.범위, 탭id, 아는카드 ? 카드id : null));
  return s ? s.번호 : 0;
}
